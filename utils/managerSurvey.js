/**
 * utils/managerSurvey.js — Dormitory Manager Questionnaire (research instrument)
 *
 * The administrator-side counterpart of utils/researchSurvey.js. Same ISO/IEC 25010
 * characteristics, same 5-point Likert scale, same interpretation bands — but the
 * statements are about running the dormitory from the admin dashboard, and the data
 * lives in its OWN table so manager results are never mixed into the resident
 * results (Chapter 3 reports the two groups separately).
 *
 * Why a separate module instead of extending researchSurvey.js: the resident
 * instrument is mid-collection; leaving that file untouched means nothing here can
 * disturb it.
 *
 * Design notes
 *   - One row per admin account (email is UNIQUE). Re-submitting updates the row,
 *     so the manager can correct an answer; updated_at records when.
 *   - Nothing derived is stored: means and interpretations are computed on read.
 *   - role is recorded with each row so a test submission from a developer/superadmin
 *     account is visible in the Research tab and can be deleted.
 */

